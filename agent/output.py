"""
Archon Output Writer

Takes the scaffolded files from agent state and writes them to disk.
Also writes the blueprint markdown.
"""

from __future__ import annotations

import os
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger("archon.output")


def write_output(state: dict[str, Any], output_dir: str = "./output") -> str:
    """
    Write all scaffolded files and the blueprint to the output directory.

    Returns:
        Summary string of what was written.
    """
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    files_written: list[str] = []

    # 1. Write the blueprint
    blueprint = state.get("blueprint_markdown", "")
    if blueprint:
        blueprint_path = output_path / "BLUEPRINT.md"
        blueprint_path.write_text(blueprint, encoding="utf-8")
        files_written.append(str(blueprint_path))
        logger.info(f"📄 Written: {blueprint_path}")

    # 2. Write all scaffolded files
    scaffolded_files = state.get("scaffolded_files", [])
    for sf in scaffolded_files:
        # Handle both dict and Pydantic model
        if hasattr(sf, "path"):
            file_path = sf.path
            content = sf.content
        else:
            file_path = sf.get("path", "")
            content = sf.get("content", "")

        if not file_path or not content:
            continue

        full_path = output_path / file_path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(content, encoding="utf-8")
        files_written.append(str(full_path))
        logger.info(f"📄 Written: {full_path}")

    # 3. Generate a summary file
    summary = state.get("scaffold_summary", "")
    project_name = state.get("project_name", "project")
    architecture_style = state.get("architecture_style", "")

    summary_content = f"""# {project_name} — Scaffold Summary

**Architecture Style:** {architecture_style}

## Generated Files

{chr(10).join(f'- `{f}`' for f in files_written)}

## Summary

{summary}

---
*Generated by Archon: The Autonomous Engineering Brain*
"""
    summary_path = output_path / "SCAFFOLD_SUMMARY.md"
    summary_path.write_text(summary_content, encoding="utf-8")
    files_written.append(str(summary_path))

    result = f"✅ Written {len(files_written)} files to {output_path.resolve()}"
    logger.info(result)
    return result
